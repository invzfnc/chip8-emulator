void Chip8::init() {
    program_counter = 0x200;
    opcode = 0;
    index_register = 0;
    stack_pointer = 0;

    // clear display
    for (int y = 0; y < SCREEN_HEIGHT; y++) {
        for (int x = 0; x < SCREEN_WIDTH; x++) {
            screen[y][x] = 0;
        }
    }

    // clear stack
    for (int i = 0; i < STACK_SIZE; i++)
        stack[i] = 0;

    // clear keys
    for (int i = 0; i < KEYS; i++)
        key[i] = 0;

    // clear memory
    for (int i = 0; i < MEMORY; i++)
        memory[i] = 0;

    // load fontset
    for (int i = 0; i < 80; i++)
        memory[i] = fontset[i];

    delay_timer = 0;
    sound_timer = 0;
}

